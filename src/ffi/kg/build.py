"""Project run data into the knowledge graph (BLUEPRINT §6 ontology)."""

from __future__ import annotations

import re
from datetime import datetime

import pandas as pd

from ffi.detectors.base import Signal
from ffi.xbrl.canonical import BY_ID, CONCEPT_TO_ITEMS

KG_FORMS = {"10-K", "10-K/A", "10-Q", "10-Q/A", "8-K", "NT 10-K", "NT 10-Q", "CORRESP", "UPLOAD",
            "20-F", "20-F/A", "40-F", "40-F/A", "NT 20-F"}

# MD&A / note paragraphs that discuss a line item AND a change create EXPLAINS edges (rule-based extractor).
ITEM_KEYWORDS: dict[str, str] = {
    "REVENUE": r"\b(?:net sales|revenues?)\b",
    "COGS": r"\bcost of (?:sales|revenues?|goods sold)\b",
    "GROSS_PROFIT": r"\bgross (?:margin|profit)\b",
    "SGA": r"\bselling, general|general and administrative|\bSG&A\b",
    "RND": r"\bresearch and development\b",
    "OPERATING_INCOME": r"\boperating (?:income|margin|profit)\b",
    "NET_INCOME": r"\bnet (?:income|earnings|loss)\b",
    "INCOME_TAX": r"\b(?:effective tax rate|provision for income taxes|income tax expense)\b",
    "AR": r"\b(?:accounts )?receivables?\b",
    "INVENTORY": r"\binventor(?:y|ies)\b",
    "CFO": r"\bcash (?:provided by|generated by|from) operat",
    "CAPEX": r"\bcapital expenditures?\b|purchases of property",
    "GOODWILL": r"\bgoodwill\b",
    "DEFERRED_REV_CURRENT": r"\bdeferred revenue|contract liabilit",
    "LONG_TERM_DEBT": r"\b(?:term debt|senior notes|borrowings)\b",
    "INTEREST_EXPENSE": r"\binterest expense\b",
    "RESTRUCTURING": r"\brestructuring\b",
    "DA": r"\bdepreciation\b",
    "SBC": r"\b(?:share|stock)-based compensation\b",
}
CHANGE_RE = re.compile(r"(?i)\b(?:increas|decreas|grew|declin|rose|fell|higher|lower|primarily due|driven by|as a result of|compared to)")


def _ts(d) -> datetime | None:
    if d is None or (isinstance(d, float) and pd.isna(d)):
        return None
    return pd.Timestamp(d).to_pydatetime()


def build(ctx) -> dict[str, int]:
    kg = ctx.kg
    kg.reset()
    cik = ctx.company.cik
    comp = f"company:{cik}"
    nodes: list[dict] = [{"id": comp, "type": "Company", "label": ctx.company.name,
                          "props": {"cik": cik, "ticker": ctx.company.ticker, "sic": ctx.company.sic}}]
    edges: list[dict] = []

    # ---- filings in the analysis window
    lo = ctx.focus - pd.Timedelta(days=6 * 366)
    for f in ctx.filings:
        if pd.Timestamp(f.filing_date) < lo or f.form not in KG_FORMS:
            continue
        fid = f"filing:{f.accession}"
        nodes.append({"id": fid, "type": "Filing", "label": f"{f.form} {f.filing_date}", "recorded_at": _ts(f.filing_date),
                      "props": {"form": f.form, "accession": f.accession, "items": f.items, "url": ctx.doc_url(f.accession)}})
        edges.append({"src": comp, "dst": fid, "type": "FILED", "recorded_at": _ts(f.filing_date)})

    # ---- line items and facts (annual + quarterly panels, plus restated versions)
    used_items: set[str] = set()
    seen_facts: set[str] = set()
    for panel in (ctx.A, ctx.Q, ctx.A_latest):
        for (item, period), rec in panel.prov.items():
            used_items.add(item)
            nid = f"fact:{rec.fact_id}"
            if nid in seen_facts:
                continue
            seen_facts.add(nid)
            nodes.append({"id": nid, "type": "Fact", "label": f"{BY_ID[item].label} {panel.label(period)}",
                          "valid_from": _ts(rec.start) or _ts(rec.end), "valid_to": _ts(rec.end), "recorded_at": _ts(rec.filed),
                          "props": {"item": item, "value": rec.val, "unit": rec.unit, "concept": f"{rec.taxonomy}:{rec.concept}",
                                    "accession": rec.accn, "period": panel.label(period)}})
            edges.append({"src": f"filing:{rec.accn}", "dst": nid, "type": "REPORTS", "recorded_at": _ts(rec.filed), "source_accession": rec.accn})
            edges.append({"src": nid, "dst": f"lineitem:{item}", "type": "INSTANCE_OF", "recorded_at": _ts(rec.filed)})
    v = ctx.store.versions("A")
    if not v.empty:
        for (item, end), g in v.groupby(["item", "end"]):
            g = g.drop_duplicates("val")
            for a, b in zip(g.iloc[:-1].itertuples(), g.iloc[1:].itertuples(), strict=True):
                na = f"version:{item}|{pd.Timestamp(end).date()}|{a.accn}"
                nb = f"version:{item}|{pd.Timestamp(end).date()}|{b.accn}"
                for n, r in ((na, a), (nb, b)):
                    nodes.append({"id": n, "type": "Fact", "label": f"{BY_ID[item].label} FY{pd.Timestamp(end).year} ({r.form} {pd.Timestamp(r.filed).date()})",
                                  "recorded_at": _ts(r.filed), "props": {"item": item, "value": float(r.val), "accession": r.accn}})
                edges.append({"src": nb, "dst": na, "type": "RESTATES", "recorded_at": _ts(b.filed), "source_accession": b.accn,
                              "props": {"delta": float(b.val - a.val)}})
                used_items.add(item)
    for item in used_items:
        it = BY_ID[item]
        nodes.append({"id": f"lineitem:{item}", "type": "LineItem", "label": it.label, "props": {"statement": it.statement, "kind": it.kind}})
    for a, b in (("GROSS_PROFIT", "REVENUE"), ("GROSS_PROFIT", "COGS"), ("PPE_NET", "PPE_GROSS"), ("PPE_NET", "ACCUM_DEP")):
        if a in used_items and b in used_items:
            edges.append({"src": f"lineitem:{b}", "dst": f"lineitem:{a}", "type": "SUMS_TO",
                          "props": {"weight": -1 if b in ("COGS", "ACCUM_DEP") else 1}})

    # ---- text: sections, spans, notes, EXPLAINS edges (rule extractor)
    for doc in ctx.docs:
        fid = f"filing:{doc.accession}"
        filed = next((f.filing_date for f in ctx.filings if f.accession == doc.accession), None)
        for sec in doc.sections:
            sid = f"section:{doc.accession}#{sec}"
            nodes.append({"id": sid, "type": "Section", "label": sec, "recorded_at": _ts(filed)})
            edges.append({"src": fid, "dst": sid, "type": "CONTAINS", "recorded_at": _ts(filed)})
        notes_seen: set[str] = set()
        for p in doc.paragraphs:
            if p.is_table_row or p.section not in ("item7", "item8", "item1a", "item9a") or len(p.text) < 60:
                continue
            nid = f"span:{p.id}"
            nodes.append({"id": nid, "type": "Span", "label": p.text[:80], "recorded_at": _ts(filed),
                          "props": {"section": p.section, "start": p.start, "end": p.end, "note": p.note, "accession": doc.accession}})
            edges.append({"src": f"section:{doc.accession}#{p.section}", "dst": nid, "type": "CONTAINS", "recorded_at": _ts(filed)})
            if p.note and p.note not in notes_seen:
                notes_seen.add(p.note)
                note_id = f"note:{doc.accession}#{p.note}"
                nodes.append({"id": note_id, "type": "Note", "label": p.note, "recorded_at": _ts(filed)})
                for item, pat in ITEM_KEYWORDS.items():
                    if item in used_items and re.search(pat, p.note, re.I):
                        edges.append({"src": note_id, "dst": f"lineitem:{item}", "type": "EXPLAINS", "recorded_at": _ts(filed),
                                      "confidence": 0.8, "extractor": "rule:note-title"})
            if p.section == "item7" and CHANGE_RE.search(p.text):
                for item, pat in ITEM_KEYWORDS.items():
                    if item in used_items and re.search(pat, p.text, re.I):
                        edges.append({"src": nid, "dst": f"lineitem:{item}", "type": "EXPLAINS", "recorded_at": _ts(filed),
                                      "confidence": 0.6, "extractor": "rule:mdna-keyword", "props": {"fy": doc.period_end}})

    # ---- auditor, events, peers
    if ctx.auditor:
        aid = f"auditor:{ctx.auditor}"
        nodes.append({"id": aid, "type": "Auditor", "label": ctx.auditor})
        edges.append({"src": comp, "dst": aid, "type": "AUDITED_BY", "recorded_at": _ts(ctx.focus)})
    for e in ctx.events:
        eid = f"event:{e.id}"
        nodes.append({"id": eid, "type": "Event", "label": f"{e.type} {e.date}", "recorded_at": _ts(e.date),
                      "props": {"event_type": e.type, "description": e.description[:300], "url": e.url}})
        edges.append({"src": comp, "dst": eid, "type": "SUBJECT_OF", "recorded_at": _ts(e.date), "source_accession": e.accession})
    if ctx.peers:
        for p in ctx.peers.peers:
            pid = f"company:{p.cik}"
            nodes.append({"id": pid, "type": "Company", "label": p.name, "props": {"cik": p.cik}})
            edges.append({"src": comp, "dst": pid, "type": "PEER_OF", "props": {"distance": p.distance}})

    kg.upsert_nodes(_dedupe(nodes))
    kg.upsert_edges(edges)
    return kg.counts()


def add_relationships(ctx) -> int:
    """E.09 relationships (verified quotes) -> Entity nodes + typed edges."""
    if not ctx.relationships or ctx.doc is None:
        return 0
    comp = f"company:{ctx.company.cik}"
    filed = next((f.filing_date for f in ctx.filings if f.accession == ctx.doc.accession), None)
    etype = {"major_customer": "SELLS_TO", "major_supplier": "BUYS_FROM", "related_party": "RELATED_PARTY",
             "guarantee": "GUARANTEES", "factoring": "SELLS_RECEIVABLES_TO", "vie": "CONSOLIDATES_OR_HOLDS_VIE",
             "side_agreement": "SIDE_AGREEMENT"}
    nodes, edges = [], []
    for r, (s, e) in ctx.relationships:
        ent = f"entity:{re.sub(r'[^a-z0-9]+', '-', r.counterparty.lower()).strip('-') or 'unnamed'}"
        nodes.append({"id": ent, "type": "Entity", "label": r.counterparty, "recorded_at": _ts(filed)})
        edges.append({"src": comp, "dst": ent, "type": etype[r.kind], "recorded_at": _ts(filed), "source_accession": ctx.doc.accession,
                      "confidence": 0.8, "extractor": f"llm:{ctx.llm.extraction_model if ctx.llm else 'n/a'}", "verified": True,
                      "props": {"amount_usd": r.amount_usd, "share_of_revenue_pct": r.share_of_revenue_pct, "new": r.is_new_this_year,
                                "span": [s, e]}})
    ctx.kg.upsert_nodes(_dedupe(nodes))
    ctx.kg.upsert_edges(edges)
    return len(edges)


def add_signals(ctx, signals: list[Signal]) -> None:
    nodes, edges = [], []
    for i, s in enumerate(signals):
        if not s.flagged:
            continue
        sid = f"signal:{s.detector_id}@{s.period}#{i}"
        nodes.append({"id": sid, "type": "Signal", "label": f"{s.detector_id} {s.name}",
                      "props": {"severity": s.severity, "area": str(s.area), "scheme": str(s.scheme) if s.scheme else None}})
        for ev in s.evidence:
            edges.append({"src": sid, "dst": ev.node_id, "type": "EVIDENCED_BY", "props": {"role": ev.role}})
            if ev.kind == "fact" and ev.concept:
                tax, _, name = ev.concept.partition(":")
                for item, _rank in CONCEPT_TO_ITEMS.get((tax, name), [])[:1]:
                    edges.append({"src": sid, "dst": f"lineitem:{item}", "type": "ABOUT"})
    ctx.kg.upsert_nodes(nodes)
    ctx.kg.upsert_edges(edges)


def _dedupe(nodes: list[dict]) -> list[dict]:
    out: dict[str, dict] = {}
    for n in nodes:
        out[n["id"]] = n
    return list(out.values())
